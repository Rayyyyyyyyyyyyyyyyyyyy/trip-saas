import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { createCanonicalTripV2Schema } from "../src/domain/trip/canonicalTripV2Schema.mjs";
import { createCanonicalTripV3Schema } from "../src/domain/trip/canonicalTripV3Schema.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const readSchema = (path) =>
  JSON.parse(readFileSync(resolve(root, path), "utf8"));

const textSourceInput = readSchema(
  "src/domain/trip/schemas/text-source-input.v1.schema.json",
);
const parsedTripDraft = readSchema(
  "src/domain/trip/schemas/parsed-trip-draft.v1.schema.json",
);
const semanticInterpretationResult = readSchema(
  "src/domain/trip/schemas/semantic-interpretation-result.v2.schema.json",
);
const canonicalTripV1 = readSchema(
  "src/domain/trip/schemas/canonical-trip.v1.schema.json",
);
const unifiedSourceDocument = readSchema(
  "src/domain/source/schemas/unified-source-document.v1.schema.json",
);
const canonicalTripV2 = createCanonicalTripV2Schema(canonicalTripV1);
const canonicalTripV3 = createCanonicalTripV3Schema(canonicalTripV2);

const ajv = new Ajv2020({
  allErrors: true,
  strict: true,
  code: { esm: true, source: true },
});
for (const schema of [
  textSourceInput,
  parsedTripDraft,
  semanticInterpretationResult,
  canonicalTripV1,
  canonicalTripV2,
  canonicalTripV3,
  unifiedSourceDocument,
]) {
  ajv.addSchema(schema);
}

const generated = standaloneCode(ajv, {
  textSourceInputValidator: textSourceInput.$id,
  parsedTripDraftValidator: parsedTripDraft.$id,
  semanticInterpretationResultValidator: semanticInterpretationResult.$id,
  canonicalTripV1Validator: canonicalTripV1.$id,
  canonicalTripV2Validator: canonicalTripV2.$id,
  canonicalTripValidator: canonicalTripV3.$id,
  unifiedSourceDocumentValidator: unifiedSourceDocument.$id,
})
  // AJV 8 emits CommonJS helpers even when the validator exports are ESM.
  // Replace the two deterministic runtime helpers so the browser bundle does
  // not depend on a global `require` and remains compatible with strict CSP.
  .replace('const func0 = require("ajv/dist/runtime/equal").default;', "")
  .replace('const func1 = require("ajv/dist/runtime/ucs2length").default;', "");
const output = resolve(
  root,
  "src/domain/generated/schemaValidators.generated.js",
);
mkdirSync(dirname(output), { recursive: true });
writeFileSync(
  output,
  `// Generated by scripts/generate-schema-validators.mjs. Do not edit.\nimport func0 from "ajv/dist/runtime/equal.js";\nimport func1 from "ajv/dist/runtime/ucs2length.js";\n${generated}\n`,
);
writeFileSync(
  output.replace(/\.js$/, ".d.ts"),
  `// Generated by scripts/generate-schema-validators.mjs. Do not edit.\nimport type { ValidateFunction } from "ajv";\n\nexport const textSourceInputValidator: ValidateFunction;\nexport const parsedTripDraftValidator: ValidateFunction;\nexport const semanticInterpretationResultValidator: ValidateFunction;\nexport const canonicalTripV1Validator: ValidateFunction;\nexport const canonicalTripV2Validator: ValidateFunction;\nexport const canonicalTripValidator: ValidateFunction;\nexport const unifiedSourceDocumentValidator: ValidateFunction;\n`,
);
